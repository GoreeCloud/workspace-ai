test('synthetic gateway rotation runs only in CI and checks stale credentials before recovery', async () => {
  const script=await readFile(fileURLToPath(new URL('../scripts/private-dev-qa-peer-rotation.sh',import.meta.url)),'utf8')
  const workflow=await readFile(fileURLToPath(new URL('../.github/workflows/private-dev-https-qa.yml',import.meta.url)),'utf8')
  const probe=await readFile(fileURLToPath(new URL('../scripts/private-dev-qa-gateway-check.sh',import.meta.url)),'utf8')
  assert.match(script,/GITHUB_ACTIONS/)
  assert.match(script,/RUNNER_TEMP/)
  assert.match(script,/openssl rand -hex 32/)
  assert.match(script,/WORKSPACE_AI_QA_EXPECT_UPSTREAM_STATUS=403/)
  assert.match(script,/--force-recreate --wait/)
  assert.match(script,/revoked direct Docker peer credential denied/)
  assert.match(script,/trap cleanup EXIT/)
  assert.doesNotMatch(script,/caddy reload|docker restart caddy|docker cp|--insecure/)
  assert.match(probe,/WORKSPACE_AI_QA_EXPECT_UPSTREAM_STATUS/)
  assert.match(probe,/200\|403/)
  assert.match(workflow,/bash scripts\/private-dev-qa-peer-rotation\.sh/)
  assert.match(workflow,/if: always\(\)/)
})
